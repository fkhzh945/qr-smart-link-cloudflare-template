export const translations = Object.fromEntries(Object.entries(baseTranslations).map(([k,v])=>[k,{...v,...activationMessages[k]}]));
function initialLocale() {
  const saved = localStorage.getItem('qr-lite-locale');
  if (saved && translations[saved]) return saved;
  return detectLocale(navigator.language || (navigator.languages || [])[0] || 'en');
}
export const locale = ref(initialLocale());
export const t = (key) => translations[locale.value]?.[key] ?? translations.en[key] ?? key;
watch(locale, value => { localStorage.setItem('qr-lite-locale', value); document.documentElement.lang=value; }, {immediate:true});
